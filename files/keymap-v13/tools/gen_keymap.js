// gen_keymap.js: layout text -> keymap.c tables.  Usage: node gen_keymap.js c100-layout-v10.txt keymap_template.c keymap.c
// The tables are written between the GENERATED markers of the template. Everything else in keymap.c is hand-written
// and must stay in step with engine.js.
// v9: 20 page slots (4 layers x 5, layer 3 has 5 pages). Every key is resolved here (page, page 1 of the layer, >C / >L,
// Controls tables), so the firmware only looks it up. The page it came from is in the top byte (0 = Controls tables).
const fs = require('fs'), load = require('./load');
const [layoutPath, tplPath, outPath] = process.argv.slice(2);
const layout = fs.readFileSync(layoutPath, 'utf8');
const C = load(false, layout);
const st = C.parseExport(layout);
const NP = C.NUM_PAGES;

const typeNames = ['none', 'trans', 'custom'].concat(Object.keys(C.TYPES).filter(k => !['none', 'trans', 'custom'].includes(k)));
const cName = k => 'T_' + k.toUpperCase();
const typeId = {}; typeNames.forEach((k, i) => typeId[k] = i);
if (typeNames.length > 255) throw new Error('too many types');

// computer keys
const KC = {SPACE: 'KC_SPC', ENTER: 'KC_ENT', TAB: 'KC_TAB', ESC: 'KC_ESC', DEL: 'KC_DEL', BSPC: 'KC_BSPC', HOME: 'KC_HOME', END: 'KC_END',
  PGUP: 'KC_PGUP', PGDN: 'KC_PGDN', MINUS: 'KC_MINS', EQUAL: 'KC_EQL', UP: 'KC_UP', DOWN: 'KC_DOWN', LEFT: 'KC_LEFT', RIGHT: 'KC_RIGHT'};
const MODS = {CTRL: 'LCTL', SHIFT: 'LSFT', ALT: 'LALT', GUI: 'LGUI'};
function kbCode(s) {
  const parts = s.toUpperCase().split('+'), key = parts.pop();
  let code = KC[key] || 'KC_' + key;
  parts.reverse().forEach(m => { code = MODS[m] + '(' + code + ')'; });
  return code;
}
const kbList = [];
function cellCode(c, from) {
  let n = c.n, z = c.z || 0;
  if (c.type === 'KB') { const s = c.s.toUpperCase(); n = kbList.indexOf(s); if (n < 0) { kbList.push(s); n = kbList.length - 1; } }
  if (n > 255) throw new Error('number too large');
  if (typeId[c.type] === undefined) throw new Error('unknown key type ' + c.type);
  return from === undefined ? 'K(' + typeId[c.type] + ',' + n + ',' + z + ')' : 'KF(' + typeId[c.type] + ',' + n + ',' + z + ',' + (from + 1) + ')';
}
// make sure arrows are the first 4 KB codes (the firmware checks them by index)
['RIGHT', 'UP', 'LEFT', 'DOWN'].forEach(k => kbList.push(k));
// resolved keys: what every key does on every page, without and with Controls Shift
const resolved = shift => Array.from({length: NP}, (_, p) => '{' + Array.from({length: 100}, (_, i) => { const r = C.resolveCell(st, p, i, shift); return cellCode(r.c, r.page); }).join(',') + '}');
const hex = h => [1, 3, 5].map(k => parseInt(h.slice(k, k + 2), 16));

const L = [];
L.push('/* ===== GENERATED by gen_keymap.js from the layout text. Do not edit by hand. ===== */');
L.push('enum key_types { ' + typeNames.map(cName).join(', ') + ', T_COUNT };');
L.push('static const uint8_t type_ctrl[T_COUNT] = {' + typeNames.map(k => C.TYPES[k] && C.TYPES[k].ctrl ? 1 : 0).join(',') + '};');
const s = st.settings;
L.push('#define KNOB_STEP ' + s.knobStep);
L.push('#define KNOB_RELATIVE ' + (s.knobMode === 'relative' ? 1 : 0));
L.push('#define TRANSPOSE_STEP ' + s.transposeStep);
L.push('#define TRANSPOSE_LIMIT ' + s.transposeLimit);
L.push('#define START_BPM ' + s.bpm);
L.push('#define SEQ_NOTE ' + s.seqNote);
L.push('#define BEND_RANGE ' + s.bendRange);
L.push('#define NUM_PAGES ' + NP);
L.push('#define NUM_SLOTS ' + C.NUM_SLOTS);
L.push('#define NUM_ZONES ' + C.NUM_ZONES);
L.push('static const uint8_t layer_pages[4] = {' + C.LAYER_PAGES.join(', ') + '};');
L.push('static const uint32_t res_keys[NUM_PAGES][100] PROGMEM = {\n    ' + resolved(false).join(',\n    ') + '\n};');
L.push('static const uint32_t res_shift[NUM_PAGES][100] PROGMEM = {\n    ' + resolved(true).join(',\n    ') + '\n};');
// control keys whose job changes with the layer, the page or Controls Shift: cyan LED (one bit per key)
L.push('static const uint8_t page_vary[NUM_PAGES][13] PROGMEM = {' + st.pages.map((_, p) => {
  const b = new Array(13).fill(0);
  for (let i = 0; i < 100; i++) if (C.controlVaries(st, p, i)) b[i >> 3] |= 1 << (i & 7);
  return '{' + b.join(',') + '}';
}).join(',\n    ') + '};');
// pages found by their keys (as in the engine: the first page that has the key)
const findPage = t => st.pages.findIndex(p => p.cells.some(c => c.type === t));
L.push('static const int8_t sq_page = ' + findPage('SQ') + ', eu_page = ' + findPage('EU') + ', sr_page = ' + findPage('SS') + ', rw_page = ' + findPage('RW') + ', cq_page = ' + findPage('CQ') + ', prog_page = ' + findPage('CP') + ', pd_page = ' + findPage('PD') + ', cn_page = ' + findPage('CN') + ';');
const fxZones = new Array(C.NUM_ZONES).fill(0);
st.pages.forEach(p => { if (p.cells.some(c => c.type === 'FX')) p.cells.forEach(c => { if (c.type === 'ZN') fxZones[c.z] = 1; }); });
L.push('static const uint8_t zone_fx[NUM_ZONES] = {' + fxZones.join(', ') + '};');
L.push('static const uint16_t kb_codes[] PROGMEM = {' + kbList.map(kbCode).join(', ') + '};');
L.push('static const uint8_t page_pal[NUM_PAGES][4][3] PROGMEM = {' + st.pages.map(pg => '{' + pg.colors.map(h => '{' + hex(h).join(',') + '}').join(',') + '}').join(',\n    ') + '};');
L.push('static const uint8_t page_chan[NUM_PAGES] PROGMEM = {' + st.pages.map(pg => pg.channel ? pg.channel - 1 : 'GLOBAL_CH').join(', ') + '};');
const LEDS = ['auto', 'solid', 'scale', 'piano', 'off'];
L.push('static const uint8_t page_led[NUM_PAGES] PROGMEM = {' + st.pages.map(pg => LEDS.indexOf(pg.led)).join(', ') + '};');
L.push('static const uint8_t zone_slot[NUM_ZONES] = {' + C.ZONE_SLOT.join(', ') + '};');
// scales
const S = C.SCALES;
L.push('#define NUM_SCALES ' + S.length);
L.push('static const uint8_t scale_len[NUM_SCALES] = {' + S.map(x => x.iv.length).join(', ') + '};');
L.push('static const uint8_t scale_iv[NUM_SCALES][12] = {' + S.map(x => '{' + x.iv.join(',') + '}').join(', ') + '};');
L.push('static const int8_t scale_dev[NUM_SCALES][12] = {' + S.map(x => '{' + x.dev.join(',') + '}').join(', ') + '};');
L.push('static const uint8_t scale_micro[NUM_SCALES] = {' + S.map(x => x.micro ? 1 : 0).join(', ') + '};');
L.push('static const uint8_t scale_bank[NUM_SCALES] = {' + S.map(x => x.bank).join(', ') + '};');
L.push('static const char scale_code[NUM_SCALES][3] = {' + S.map(x => '"' + x.code + '"').join(',') + '};');
L.push('static const uint8_t bank_first[2] = {' + C.BANK_FIRST.join(', ') + '}, bank_size[2] = {' + C.BANK_SIZE.join(', ') + '};');
// microtonal tunings: pad cents in quarter cents (pads 0-63, row-major from the bottom-left)
L.push('#define NUM_TUNINGS ' + C.TUNINGS.length);
L.push('static const char tuning_code[NUM_TUNINGS][3] = {' + C.TUNINGS.map(t => '"' + t.code + '"').join(',') + '};');
L.push('static const uint8_t tuning_base[NUM_TUNINGS] = {' + C.TUNING_BASE.join(', ') + '};');
L.push('static const uint16_t tuning_q[NUM_TUNINGS][64] PROGMEM = {' + C.TUNINGS.map((_, t) => '{' + Array.from({length: 64}, (_, n) => Math.round(C.tuningCents(t, n % 8, n >> 3) * 4)).join(',') + '}').join(',\n    ') + '};');
// font
const chars = Object.keys(C.FONT).join('');
L.push('static const char FONT_CHARS[] = ' + JSON.stringify(chars) + ';');
L.push('static const uint16_t font_glyphs[] PROGMEM = {' + Object.values(C.FONT).map(g => '0x' + parseInt(g.join(''), 2).toString(16).padStart(4, '0')).join(', ') + '};');
L.push('/* ===== end of GENERATED ===== */');

const tpl = fs.readFileSync(tplPath, 'utf8');
const a = tpl.indexOf('/*@@GENERATED@@*/');
if (a < 0) throw new Error('template has no /*@@GENERATED@@*/ marker');
fs.writeFileSync(outPath, tpl.slice(0, a) + L.join('\n') + tpl.slice(a + '/*@@GENERATED@@*/'.length));
console.log('wrote', outPath, '-', typeNames.length, 'key types,', kbList.length, 'computer keys,', NP, 'page slots');
